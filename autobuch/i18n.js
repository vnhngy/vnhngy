// Sprachen: Deutsch ist die Ausgangssprache. Die deutschen Texte im Code sind zugleich die Schlüssel
// für die Übersetzungen in T (unten): 'Deutsch': ['English', 'Tiếng Việt'].

const LANGS = { de: 'de-DE', en: 'en-GB', vi: 'vi-VN' };
let LANG = 'de';
let LOCALE = LANGS.de;
const MISSING = new Set(); // fehlende Übersetzungen (zum Testen)

function detectLang() {
  const l = (navigator.language || 'de').slice(0, 2).toLowerCase();
  return LANGS[l] ? l : 'de';
}

function initLang(l) {
  LANG = LANGS[l] ? l : detectLang();
  LOCALE = LANGS[LANG];
  document.documentElement.lang = LANG;
}

// Übersetzt einen Text und setzt {platzhalter} ein
function tr(key, vars) {
  let s = key;
  if (LANG !== 'de' && key) {
    const entry = T[key];
    if (entry) s = entry[LANG === 'en' ? 0 : 1];
    else if (/[A-Za-zÄÖÜäöüß]/.test(key)) MISSING.add(key);
  }
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return s;
}

// Feste Texte im HTML: einmal einsammeln, bei jedem Sprachwechsel neu setzen.
// Eine „Einheit“ ist ein Element mit Text, das nur Inline-Elemente (b, small, a, span …) enthält.
const STATIC = [];
const INLINE = new Set(['B', 'STRONG', 'SMALL', 'A', 'BR', 'SPAN', 'EM', 'I']);
const norm = (h) => h.replace(/\s+/g, ' ').trim();

function collectStatic(root = document.body) {
  const walk = (el) => {
    for (const a of ['placeholder', 'aria-label', 'title']) {
      if (el.hasAttribute(a)) STATIC.push({ el, attr: a, src: el.getAttribute(a) });
    }
    if (el.matches('script, style, svg, dialog, [data-noi18n]')) return;
    const kids = [...el.childNodes];
    const hasText = kids.some((n) => n.nodeType === 3 && n.textContent.trim());
    const inlineOnly = [...el.children].every((c) => INLINE.has(c.tagName) && [...c.children].every((g) => INLINE.has(g.tagName)));
    if (hasText && inlineOnly) { STATIC.push({ el, src: norm(el.innerHTML) }); return; }
    for (const n of kids) {
      if (n.nodeType === 3 && n.textContent.trim()) STATIC.push({ node: n, src: n.textContent.trim() });
      else if (n.nodeType === 1) walk(n);
    }
  };
  walk(root);
}

function applyStatic() {
  for (const x of STATIC) {
    const v = tr(x.src);
    if (x.attr) x.el.setAttribute(x.attr, v);
    else if (x.node) x.node.textContent = ' ' + v + ' ';
    else x.el.innerHTML = v;
  }
}

